import { chromium } from '@playwright/test';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const output = path.join(root, 'screenshots');
fs.mkdirSync(output, { recursive: true });
const browser = await chromium.launch({ channel: 'msedge', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 1 });
const errors = [];
page.on('pageerror', (error) => errors.push(error.message));
page.on('console', (message) => { if (message.type() === 'error') errors.push(`${message.text()} @ ${message.location().url || 'unknown'}`); });
page.on('response', (response) => { if (response.status() >= 400) errors.push(`${response.status()} ${response.url()}`); });
page.on('requestfailed', (request) => errors.push(`FAILED ${request.url()} ${request.failure()?.errorText || ''}`));
await page.addInitScript(() => localStorage.clear());
await page.goto('http://127.0.0.1:4173/', { waitUntil: 'networkidle' });
await page.getByRole('button', { name: '跳过引导' }).click();
await page.locator('#player-name').fill('探索者');
await page.locator('[data-skin="amber"]').click();
await page.getByRole('button', { name: '开启旅程' }).click();
await page.waitForTimeout(500);
await page.screenshot({ path: path.join(output, 'home-atlas-home.png'), fullPage: true });
await page.evaluate(() => window.__HOME_ATLAS_DEBUG__.moveHomeTo('kitchen'));
await page.keyboard.press('Space');
await page.keyboard.press('r');
await page.evaluate(() => window.__HOME_ATLAS_DEBUG__.moveSceneToFirstWord());
await page.waitForTimeout(1500);
await page.screenshot({ path: path.join(output, 'home-atlas-kitchen.png'), fullPage: true });
await browser.close();
console.log(JSON.stringify({ screenshots: ['screenshots/home-atlas-home.png', 'screenshots/home-atlas-kitchen.png'], errors }, null, 2));
if (errors.length) process.exitCode = 1;
