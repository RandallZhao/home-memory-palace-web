import { chromium } from '@playwright/test';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const output = path.join(root, 'screenshots', 'comparisons', 'after');
fs.mkdirSync(output, { recursive: true });
const browser = await chromium.launch({ channel: 'msedge', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 1 });
const errors = [];
const baseURL = process.env.BASE_URL || 'http://127.0.0.1:4173/';
page.on('pageerror', (error) => errors.push(error.message));
page.on('console', (message) => { if (message.type() === 'error') errors.push(`${message.text()} @ ${message.location().url || 'unknown'}`); });
page.on('response', (response) => { if (response.status() >= 400) errors.push(`${response.status()} ${response.url()}`); });
page.on('requestfailed', (request) => errors.push(`FAILED ${request.url()} ${request.failure()?.errorText || ''}`));
await page.addInitScript(() => localStorage.clear());
await page.goto(baseURL, { waitUntil: 'networkidle' });
await page.getByRole('button', { name: '跳过引导' }).click();
await page.locator('#player-name').fill('探索者');
await page.locator('[data-skin="amber"]').click();
await page.getByRole('button', { name: '开启旅程' }).click();
await page.waitForTimeout(500);
for (const [width, height] of [[1280, 720], [1440, 900], [1920, 1080]]) {
  await page.setViewportSize({ width, height });
  await page.waitForTimeout(180);
  await page.screenshot({ path: path.join(output, `home-${width}x${height}.png`), fullPage: true });
}

await page.setViewportSize({ width: 1440, height: 900 });
await page.evaluate(() => window.__HOME_ATLAS_DEBUG__.moveHomeTo('recreationroom'));
await page.keyboard.press('Space');
await page.keyboard.press('r');
await page.waitForTimeout(700);
await page.evaluate(() => window.__HOME_ATLAS_DEBUG__.moveSceneToWord('recreationroom.manga_cove.comic_book'));
await page.waitForTimeout(1500);
await page.screenshot({ path: path.join(output, 'study-low-density-1440x900.png'), fullPage: true });

await page.evaluate(() => localStorage.clear());
await page.reload({ waitUntil: 'networkidle' });
await page.getByRole('button', { name: '跳过引导' }).click();
await page.locator('#player-name').fill('探索者');
await page.locator('[data-skin="amber"]').click();
await page.getByRole('button', { name: '开启旅程' }).click();
await page.evaluate(() => window.__HOME_ATLAS_DEBUG__.moveHomeTo('washroom'));
await page.keyboard.press('Space');
await page.keyboard.press('r');
await page.waitForTimeout(700);
await page.evaluate(() => window.__HOME_ATLAS_DEBUG__.moveSceneToWord('washroom.shower_area.shower'));
await page.setViewportSize({ width: 1920, height: 1080 });
await page.waitForTimeout(1500);
await page.screenshot({ path: path.join(output, 'study-high-density-1920x1080.png'), fullPage: true });

await page.evaluate(() => localStorage.clear());
await page.reload({ waitUntil: 'networkidle' });
await page.getByRole('button', { name: '跳过引导' }).click();
await page.locator('#player-name').fill('探索者');
await page.locator('[data-skin="amber"]').click();
await page.getByRole('button', { name: '开启旅程' }).click();
await page.evaluate(() => window.__HOME_ATLAS_DEBUG__.moveHomeTo('kitchen'));
await page.keyboard.press('Space');
await page.keyboard.press('f');
await page.waitForTimeout(700);
await page.evaluate(() => window.__HOME_ATLAS_DEBUG__.moveSceneToFirstWord());
await page.setViewportSize({ width: 1440, height: 900 });
await page.waitForTimeout(1200);
await page.screenshot({ path: path.join(output, 'practice-input-1440x900.png'), fullPage: true });
await page.keyboard.press('/');
await page.waitForTimeout(250);
await page.setViewportSize({ width: 1280, height: 720 });
await page.screenshot({ path: path.join(output, 'system-help-1280x720.png'), fullPage: true });
await browser.close();
console.log(JSON.stringify({ output, errors }, null, 2));
if (errors.length) process.exitCode = 1;
